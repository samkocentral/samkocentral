'use client';

export interface AuditDiff {
  field: string;
  previous: string;
  current: string;
}

export interface AuditLogEntry {
  id: string;
  timestamp: string; // YYYY-MM-DD HH:mm:ss
  relativeTime: string;
  actorName: string;
  actorEmail: string;
  actorInitials: string;
  roleLevel: string;
  action:
    'LOGIN' | 'CREATE' | 'UPDATE' | 'DELETE' | 'ROLE_SWITCH' | 'EXPORT' | 'SECURITY' | 'SIGN_OFF';
  actionLabel: string;
  category:
    'AUTH' | 'USER_MANAGEMENT' | 'ASSET_REGISTER' | 'COMPLIANCE' | 'MAINTENANCE' | 'SECURITY';
  categoryLabel: string;
  resource: string;
  property?: string;
  ipAddress: string;
  location: string;
  userAgent?: string;
  status: 'success' | 'warning' | 'alert';
  details: string;
  diff?: AuditDiff[];
}

const STORAGE_KEY = 'samko_real_audit_logs';

function formatDateTime(d: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0');
  const year = d.getFullYear();
  const month = pad(d.getMonth() + 1);
  const day = pad(d.getDate());
  const hours = pad(d.getHours());
  const minutes = pad(d.getMinutes());
  const seconds = pad(d.getSeconds());
  return `${year}-${month}-${day} ${hours}:${minutes}:${seconds}`;
}

export function computeRelativeTime(dateString: string): string {
  try {
    const time = new Date(dateString.replace(' ', 'T')).getTime();
    const diffMs = Date.now() - time;
    if (diffMs < 0 || isNaN(diffMs)) return 'Just now';
    const diffSec = Math.floor(diffMs / 1000);
    if (diffSec < 60) return 'Just now';
    const diffMin = Math.floor(diffSec / 60);
    if (diffMin < 60) return `${diffMin}m ago`;
    const diffHours = Math.floor(diffMin / 60);
    if (diffHours < 24) return `${diffHours}h ago`;
    const diffDays = Math.floor(diffHours / 24);
    if (diffDays === 1) return 'Yesterday';
    if (diffDays < 30) return `${diffDays}d ago`;
    return dateString.split(' ')[0];
  } catch {
    return 'Recently';
  }
}

// Check if a log was generated by or belongs to Digital Bot
export function isBotLog(log: AuditLogEntry): boolean {
  const email = (log.actorEmail || '').toLowerCase();
  const name = (log.actorName || '').toLowerCase();
  const resource = (log.resource || '').toLowerCase();
  const details = (log.details || '').toLowerCase();
  const actionLabel = (log.actionLabel || '').toLowerCase();
  return (
    email.includes('digitalbot') ||
    email.includes('system.security') ||
    name.includes('digital bot') ||
    name.includes('security daemon') ||
    name.includes('automated bot') ||
    resource.includes('digital bot') ||
    resource.includes('governance vault') ||
    resource.includes('cms schema store') ||
    resource.includes('portfolio compliance matrix') ||
    details.includes('digital bot') ||
    actionLabel.includes('access boundary check') ||
    actionLabel.includes('cms store sync') ||
    actionLabel.includes('statutory health sweep')
  );
}

// Identify any dummy, mock, or synthetic seed logs to permanently purge them
export function isDummyOrMockLog(log: AuditLogEntry): boolean {
  if (!log) return true;
  const id = log.id || '';
  const details = (log.details || '').toLowerCase();
  const actionLabel = (log.actionLabel || '').toLowerCase();
  const resource = (log.resource || '').toLowerCase();

  return (
    id.startsWith('AUD-INIT-') ||
    id.startsWith('AUD-BOT-') ||
    id.startsWith('AUD-94') ||
    actionLabel.includes('access boundary check') ||
    actionLabel.includes('cms store sync') ||
    actionLabel.includes('statutory health sweep') ||
    actionLabel.includes('annual portfolio sign-off') ||
    actionLabel.includes('certificate auto-renewed') ||
    resource.includes('governance vault') ||
    resource.includes('cms schema store') ||
    resource.includes('portfolio compliance matrix') ||
    resource.includes('statutory certification dossier') ||
    resource.includes('tls/ssl wildcard') ||
    details.includes('automated let’s encrypt') ||
    details.includes('internal daemon loop') ||
    details.includes('simulated')
  );
}

export function isMockDaemonLog(log: AuditLogEntry): boolean {
  return isDummyOrMockLog(log);
}

