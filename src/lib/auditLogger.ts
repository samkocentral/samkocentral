/**
 * Returns the current list of real audit logs.
 * Strictly hides Digital Bot logs from all standard users and admins!
 */
export function getRealAuditLogs(currentUser?: any): AuditLogEntry[] {
  let storedLogs: AuditLogEntry[] = [];

  if (typeof window !== 'undefined') {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (raw) {
        const parsed = JSON.parse(raw);
        if (Array.isArray(parsed) && parsed.length > 0) {
          // Immediately purge any legacy mock daemon entries that were artificially created
          const sanitized = parsed.filter((l) => !isMockDaemonLog(l));
          if (sanitized.length > 0) {
            storedLogs = sanitized;
          }
        }
      }
    } catch (e) {
      console.warn('[auditLogger] Failed to read logs from localStorage:', e);
    }
  }

  // Zero dummy logs rule: If empty, remain clean live empty array []
  if (storedLogs.length === 0) {
    storedLogs = [];
  }

  // Update relative time dynamically
  storedLogs = storedLogs.map((l) => ({
    ...l,
    relativeTime: computeRelativeTime(l.timestamp),
  }));

  // Determine if the currently logged in user is strictly the Digital Bot
  let activeUser = currentUser;
  if (!activeUser && typeof window !== 'undefined') {
    try {
      const userRaw = localStorage.getItem('samko_auth_user');
      if (userRaw) activeUser = JSON.parse(userRaw);
    } catch {}
  }

  // Check if originalAdmin is set (which means someone is previewing as another user)
  let isPreviewMode = false;
  if (typeof window !== 'undefined') {
    try {
      isPreviewMode = Boolean(localStorage.getItem('samko_original_admin'));
    } catch {}
  }

  const isStrictDigitalBot = Boolean(
    !isPreviewMode &&
    (activeUser?.id === 'usr-bot-001' ||
      activeUser?.email?.toLowerCase() === 'digitalbot@samkocentral.com' ||
      activeUser?.name?.toLowerCase().includes('digital bot'))
  );

  // Filter logs strictly through multi-tier role clearance and privacy boundaries
  storedLogs = storedLogs.filter((log) => canUserViewAuditLog(activeUser, log));

  return storedLogs;
}

/**
 * Evaluates whether a given user has clearance to view a specific audit log entry.
 * Strictly prevents administrative actions, role impersonations, and higher-level
 * audit events from leaking to lower roles (e.g. David Park L4, Sarah Chen L3, etc.).
 */
export function canUserViewAuditLog(user: any, log: AuditLogEntry): boolean {
  if (!user) return false;

  const role = user.roleLevel || 'L4';
  const userEmail = (user.email || '').toLowerCase();
  const logActorEmail = (log.actorEmail || '').toLowerCase();
  const isSelf = Boolean(userEmail && logActorEmail === userEmail);

  // 1. Digital Bot strict isolation: bot logs are visible ONLY to the actual bot session
  if (isBotLog(log)) {
    const isStrictBot =
      user.id === 'usr-bot-001' ||
      userEmail === 'digitalbot@samkocentral.com' ||
      (user.name || '').toLowerCase().includes('digital bot');
    if (!isStrictBot) return false;
  }

  // 2. Sensitive Governance Sealing:
  // - ROLE_SWITCH: Role impersonation / previewing another user's view (e.g. "Role Switched to Viewer (L4)")
  // - SECURITY: Internal security audits, token verifications, boundary enforcement
  // These are strictly confidential governance operations visible ONLY to authentic L1 Super Admin!
  if (log.action === 'ROLE_SWITCH' || log.category === 'SECURITY') {
    return role === 'L1';
  }

  // 3. Super Admin (L1) has full governance visibility across all legitimate records
  if (role === 'L1') {
    return true;
  }

  // 4. Sealing Super Admin (L1) actions from lower roles:
  // Lower roles (L2, L3, L4) must NEVER see actions executed by Super Admin (L1)
  // (e.g., Alexander Vance sessions, admin sign-outs, or admin edits to accounts).
  if (log.roleLevel === 'L1' && !isSelf) {
    return false;
  }

  // 5. Authentication (AUTH) Events (Login / Logout):
  // Users below L1 can ONLY see their own login/logout history.
  // David Park (L4) must never see Marcus Webb (L2) or Alexander Vance (L1) signing in or out.
  if (log.category === 'AUTH') {
    return isSelf;
  }

  // 6. User Management (USER_MANAGEMENT) Events:
  // L3 (Uploader) and L4 (Viewer) must NEVER see user management logs (adding/deleting users, role changes).
  if (log.category === 'USER_MANAGEMENT') {
    if (role === 'L3' || role === 'L4') return false;
    if (role === 'L2') {
      return isPortalAllowed(user, log);
    }
  }

  // 7. Property / Site Boundary Clearance:
  // Standard operational logs (ASSET_REGISTER, COMPLIANCE, MAINTENANCE)
  // must match the user's assigned properties if they are restricted.
  return isPropertyAllowed(user, log.property);
}

export function isPropertyAllowed(user: any, logProperty?: string): boolean {
  if (
    !logProperty ||
    logProperty === 'All Properties (Portfolio)' ||
    logProperty === 'Portfolio Asset'
  ) {
    return true;
  }
  const assigned = user?.assignedProperties;
  if (!assigned || !Array.isArray(assigned) || assigned.length === 0 || assigned.includes('all')) {
    return true;
  }
  const cleanLogProp = logProperty.toLowerCase();
  return assigned.some((p: string) => cleanLogProp.includes(p.toLowerCase()));
}

export function isPortalAllowed(user: any, log: AuditLogEntry): boolean {
  const portal = user?.portal;
  if (!portal || portal === 'both') return true;
  const prop = (log.property || '').toLowerCase();
  const details = (log.details || '').toLowerCase();
  if (portal === 'propco' && (prop.includes('opco') || details.includes('opco portal'))) {
    return false;
  }
  if (portal === 'opco' && (prop.includes('propco') || details.includes('propco portal'))) {
    return false;
  }
  return true;
}

/**
 * Records a real audit log entry whenever any real action is taken in the application.
 */
export function recordAuditLog(entry: Partial<AuditLogEntry>): AuditLogEntry {
  let activeUser: any = null;
  if (typeof window !== 'undefined') {
    try {
      const userRaw = localStorage.getItem('samko_auth_user');
      if (userRaw) activeUser = JSON.parse(userRaw);
    } catch {}
  }

  const actorName = entry.actorName || activeUser?.name || 'Alexander Vance';
  const actorEmail = entry.actorEmail || activeUser?.email || 'superadmin@samkocentral.com';
  const roleLevel = entry.roleLevel || activeUser?.roleLevel || 'L1';
  const actorInitials =
    entry.actorInitials ||
    activeUser?.initials ||
    actorName
      .split(' ')
      .map((n: string) => n[0])
      .join('')
      .slice(0, 2)
      .toUpperCase() ||
    'AV';

  const now = new Date();
  const fullTimestamp = formatDateTime(now);

  const newLog: AuditLogEntry = {
    id: entry.id || `AUD-${Date.now()}-${Math.floor(Math.random() * 900 + 100)}`,
    timestamp: entry.timestamp || fullTimestamp,
    relativeTime: 'Just now',
    actorName,
    actorEmail,
    actorInitials,
    roleLevel: roleLevel as any,
    action: entry.action || 'UPDATE',
    actionLabel: entry.actionLabel || 'Action Executed',
    category: entry.category || 'ASSET_REGISTER',
    categoryLabel: entry.categoryLabel || entry.category || 'Asset Register',
    resource: entry.resource || 'Platform Resource',
    property: entry.property || activeUser?.hotel || 'All Properties (Portfolio)',
    ipAddress: entry.ipAddress || '86.154.21.90 (Current Session)',
    location: entry.location || 'London, United Kingdom',
    status: entry.status || 'success',
    details: entry.details || `${actorName} executed ${entry.actionLabel || 'an operation'}.`,
    diff: entry.diff || undefined,
  };

  if (typeof window !== 'undefined') {
    try {
      const existingRaw = localStorage.getItem(STORAGE_KEY);
      let existing: AuditLogEntry[] = [];
      if (existingRaw) {
        existing = JSON.parse(existingRaw);
      }
      if (!Array.isArray(existing)) existing = [];
      const updated = [newLog, ...existing].slice(0, 500);
      localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));

      // Broadcast custom event so Audit Logs page and Dashboard widget update instantly
      window.dispatchEvent(new CustomEvent('samko:audit-log-created', { detail: newLog }));
      window.dispatchEvent(
        new CustomEvent('samko:data-changed', { detail: { type: 'audit-log', entry: newLog } })
      );
    } catch (e) {
      console.warn('[auditLogger] Failed to write log to localStorage:', e);
    }

    // Fire and forget POST to server API
    fetch('/api/audit-logs', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(newLog),
    }).catch(() => {});
  }

  return newLog;
}

export function exportAuditLogsToCSV(logs: AuditLogEntry[]) {
  const headers = [
    'Event ID',
    'Timestamp',
    'Actor Name',
    'Actor Email',
    'Role Level',
    'Action',
    'Category',
    'Property',
    'Target Resource',
    'IP Address',
    'Location',
    'Status',
    'Details',
  ];

  const rows = logs.map((l) => [
    l.id,
    l.timestamp,
    `"${l.actorName.replace(/"/g, '""')}"`,
    `"${l.actorEmail.replace(/"/g, '""')}"`,
    l.roleLevel,
    l.action,
    l.category,
    `"${(l.property || 'Portfolio-wide').replace(/"/g, '""')}"`,
    `"${l.resource.replace(/"/g, '""')}"`,
    l.ipAddress,
    `"${l.location.replace(/"/g, '""')}"`,
    l.status,
    `"${l.details.replace(/"/g, '""')}"`,
  ]);

  const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute(
    'download',
    `SamkoCentral_Audit_Logs_${new Date().toISOString().slice(0, 10)}.csv`
  );
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

/**
 * Hard reset: purges all stored audit logs from both localStorage and server,
 * resetting the platform audit ledger to a pristine 100% clean live state.
 */
export function resetAuditLogs(): void {
  if (typeof window !== 'undefined') {
    try {
      localStorage.removeItem(STORAGE_KEY);
      localStorage.removeItem('samko_recent_logs');
      localStorage.setItem(STORAGE_KEY, JSON.stringify([]));
      window.dispatchEvent(new CustomEvent('samko:audit-logs-updated'));
      window.dispatchEvent(
        new CustomEvent('samko:data-changed', { detail: { type: 'audit-log' } })
      );
    } catch {}
    fetch('/api/audit-logs', { method: 'DELETE' }).catch(() => {});
  }
}
